from abc import ABC, abstractmethod
from collections.abc import Sequence
from dataclasses import dataclass
from typing import Literal, TypeVar

from pydantic import BaseModel

LlmRole = Literal["system", "user", "assistant"]

StructuredOutput = TypeVar("StructuredOutput", bound=BaseModel)


@dataclass(frozen=True)
class LlmMessage:
    """A message exchanged with a language model."""

    role: LlmRole
    content: str


@dataclass(frozen=True)
class LlmUsage:
    """Token usage reported by the provider, when available."""

    input_tokens: int
    output_tokens: int


@dataclass(frozen=True)
class LlmReply:
    """The text generated by the model, with provenance."""

    text: str
    model: str
    usage: LlmUsage | None = None


class StructuredOutputError(Exception):
    """O modelo respondeu, mas o output não casa com o schema pedido.

    É a tradução, na fronteira do port, das falhas de parsing/validação do
    provedor (JSON malformado, campo fora do enum, tipo errado). `attempts`
    conta quantas tentativas produziram este erro; `detail` resume a causa sem
    carregar o conteúdo do prompt.
    """

    def __init__(self, attempts: int, detail: str):

        super().__init__(
            f"output estruturado inválido após {attempts} tentativa(s): {detail}"
        )
        self.attempts = attempts
        self.detail = detail


# Outbound (driven) port: the application depends on this interface; the
# LangChain adapter implements it. No langchain type crosses this boundary.
# `step` labels the call (`planner`, `insight`) so usage and latency are
# recorded per step; it never changes what is sent to the model.
class LlmPort(ABC):
    """Generates a text reply from a sequence of messages."""

    @abstractmethod
    async def generate(
        self,
        messages: Sequence[LlmMessage],
        session_id: str | None = None,
        step: str = "llm",
    ) -> LlmReply: ...

    @abstractmethod
    async def generate_structured(
        self,
        messages: Sequence[LlmMessage],
        schema: type[StructuredOutput],
        session_id: str | None = None,
        step: str = "llm",
    ) -> StructuredOutput: ...
